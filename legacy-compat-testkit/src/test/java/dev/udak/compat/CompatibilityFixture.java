package dev.udak.compat;

import static dev.udak.compat.LegacyCompatibilityTest.QUERY_TIMEOUT_SECONDS;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import javax.sql.DataSource;

final class CompatibilityFixture implements AutoCloseable {
    private final DataSource dataSource;
    private final Profile profile;
    private Connection connection;
    private boolean created;

    CompatibilityFixture(DataSource dataSource, String profile) {
        this.dataSource = dataSource;
        try {
            this.profile = Profile.valueOf(profile);
        } catch (IllegalArgumentException | NullPointerException failure) {
            throw new LegacyCompatibilityTest.Failure("INVALID_PROFILE");
        }
    }

    void create() {
        try {
            // Keep the in-memory database alive between the two framework stacks.
            connection = dataSource.getConnection();
            if (!connection.getAutoCommit()) throw new LegacyCompatibilityTest.Failure("FIXTURE_AUTOCOMMIT_REQUIRED");
            if (!profile.product.equalsIgnoreCase(connection.getMetaData().getDatabaseProductName())) {
                throw new LegacyCompatibilityTest.Failure("PRODUCT_MISMATCH");
            }
            if (exists()) throw new LegacyCompatibilityTest.Failure("PREEXISTING_FIXTURE");
            try (Statement statement = connection.createStatement()) {
                statement.setQueryTimeout(QUERY_TIMEOUT_SECONDS);
                statement.executeUpdate("CREATE TABLE app_user (id " + profile.identity + " PRIMARY KEY, name "
                        + profile.nameType + "(255) NOT NULL)");
                // A successful plain CREATE is the only condition authorizing DROP.
                created = true;
            }
            if (!exists()) throw new LegacyCompatibilityTest.Failure("FIXTURE_CREATION_UNCONFIRMED");
        } catch (SQLException failure) {
            throw new LegacyCompatibilityTest.Failure("FIXTURE_BOOTSTRAP", failure);
        }
    }

    void clearRows() {
        try (Statement statement = connection.createStatement()) {
            statement.setQueryTimeout(QUERY_TIMEOUT_SECONDS);
            statement.executeUpdate("DELETE FROM app_user");
        } catch (SQLException failure) {
            throw new LegacyCompatibilityTest.Failure("FIXTURE_RESET", failure);
        }
    }

    private boolean exists() throws SQLException {
        DatabaseMetaData metadata = connection.getMetaData();
        String table = metadata.storesUpperCaseIdentifiers() ? "APP_USER" : "app_user";
        // A match in any visible schema is sufficient to preserve the preexisting object.
        try (ResultSet matches = metadata.getTables(null, null, table, null)) {
            while (matches.next()) {
                if (table.equalsIgnoreCase(matches.getString("TABLE_NAME"))) return true;
            }
            return false;
        }
    }

    @Override
    public void close() {
        if (connection == null) return;
        try (Connection current = connection) {
            if (created) {
                try (Statement statement = current.createStatement()) {
                    statement.setQueryTimeout(QUERY_TIMEOUT_SECONDS);
                    statement.executeUpdate(profile == Profile.ORACLE ? "DROP TABLE app_user PURGE" : "DROP TABLE app_user");
                }
                if (exists()) throw new LegacyCompatibilityTest.Failure("FIXTURE_CLEANUP_UNCONFIRMED");
            }
        } catch (SQLException failure) {
            throw new LegacyCompatibilityTest.Failure("FIXTURE_CLEANUP_FAILED", failure);
        }
    }

    private enum Profile {
        H2("H2", "BIGINT GENERATED BY DEFAULT AS IDENTITY", "VARCHAR"),
        POSTGRESQL("PostgreSQL", "BIGINT GENERATED BY DEFAULT AS IDENTITY", "VARCHAR"),
        MYSQL("MySQL", "BIGINT AUTO_INCREMENT", "VARCHAR"),
        SQLSERVER("Microsoft SQL Server", "BIGINT IDENTITY(1,1)", "VARCHAR"),
        ORACLE("Oracle", "NUMBER(19) GENERATED BY DEFAULT AS IDENTITY", "VARCHAR2");

        private final String product;
        private final String identity;
        private final String nameType;

        Profile(String product, String identity, String nameType) {
            this.product = product;
            this.identity = identity;
            this.nameType = nameType;
        }
    }
}
